
import json
import subprocess
from pathlib import Path

project_dir = Path(__file__).resolve().parent.parent
json_file = Path(__file__).resolve().parent / "recipes.json"
seed_file = project_dir / "src" / "init_data" / "recipes_seed.sql"

with open(json_file, "r", encoding="utf-8") as file:
    recipes = json.load(file)

def sql_string(value):
    return "'" + str(value).replace("'", "''") + "'"

sql_commands = ["BEGIN;"]

for recipe in recipes:
    name = sql_string(recipe["name"])
    description = sql_string(recipe["description"])
    instructions = sql_string(recipe["instructions"])

    prep_time = int(recipe["prep_time"])
    cook_time = int(recipe["cook_time"])
    servings = int(recipe["servings"])

    ingredient_rows = []

    for ingredient in recipe["ingredients"]:
        ingredient_rows.append(
            f"({sql_string(ingredient['name'])}, "
            f"{float(ingredient['quantity'])}, "
            f"{sql_string(ingredient['unit'])})"
        )

    values = ",\n".join(ingredient_rows)

    sql_commands.append(f"""
WITH new_recipe AS (
    INSERT INTO recipes (
        name, description, instructions,
        prep_time, cook_time, servings
    )
    SELECT
        {name}, {description}, {instructions},
        {prep_time}, {cook_time}, {servings}
    WHERE NOT EXISTS (
        SELECT 1
        FROM recipes
        WHERE LOWER(name) = LOWER({name})
    )
    RETURNING recipe_id
)
INSERT INTO recipe_ingredients (
    recipe_id, ingredient_name, quantity, unit
)
SELECT
    new_recipe.recipe_id,
    ingredient_name,
    quantity,
    unit
FROM new_recipe
CROSS JOIN (
    VALUES {values}
) AS ingredient_list(ingredient_name, quantity, unit);
""")

sql_commands.append("COMMIT;")
sql = "\n".join(sql_commands)

# Write the seed file so a fresh database loads every recipe on docker compose up
with open(seed_file, "w", encoding="utf-8") as file:
    file.write("-- Generated by recipe_dataset/import_recipes.py, do not edit by hand\n")
    file.write(sql + "\n")

print(f"Wrote {len(recipes)} recipes to {seed_file.relative_to(project_dir)}")

# Also load them into the database that is already running, if there is one
result = subprocess.run(
    [
        "docker", "compose", "exec", "-T", "db",
        "sh", "-c",
        'psql -q -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB"'
    ],
    input=sql,
    text=True,
    encoding="utf-8",
    cwd=project_dir
)

if result.returncode == 0:
    print(f"Successfully imported {len(recipes)} recipes into the running database!")
else:
    print("Could not import into the running database. Start it with docker compose up,")
    print("or run docker compose down -v and docker compose up to load the seed file.")
